def _num_ok(paper, obs, tol):
    if isinstance(paper, list):
        return len(paper) == len(obs) and all(abs(float(o) - float(p)) <= tol for p, o in zip(paper, obs))
    return abs(float(obs) - float(paper)) <= tol


def judge(c: Claim):
    try:
        obs = c.observe()
    except Exception as e:  # missing output -> hard failure
        return f"ERROR: {type(e).__name__}: {e}", "ERROR", False
    if c.cid == "X1":                       # runtime is reported, never gated
        return obs, c.expected, True
    if c.expected in ("NOT_SUPPORTED",):
        # A NOT_SUPPORTED claim is confirmed when the observation differs from the paper.
        matches = (str(obs) == str(c.paper)) if c.tol is None else _num_ok(c.paper, obs, c.tol)
        status = "REPRODUCED" if matches else "NOT_SUPPORTED"
        return obs, status, status == c.expected
    if c.tol == "max<":
        ok = float(obs) < float(c.paper)
    elif c.tol is None:
        ok = str(obs) == str(c.paper)
    else:
        ok = _num_ok(c.paper, obs, c.tol)
    status = c.expected if ok else "MISMATCH"
    return obs, status, ok


def fmt(v):
    if isinstance(v, list):
        return " / ".join(fmt(x) for x in v)
    if isinstance(v, float):
        return f"{v:,.4f}".rstrip("0").rstrip(".") if abs(v) < 100 else f"{v:,.1f}"
    return str(v)


def main() -> int:
    rows = []
    for c in CLAIMS:
        obs, status, ok = judge(c)
        rows.append(dict(id=c.cid, section=c.section, claim=c.statement, paper_value=fmt(c.paper),
                         regenerated_value=fmt(obs), status=status, documented_status=c.expected,
                         as_documented=ok, erratum=c.erratum, evidence=c.evidence))
    df = pd.DataFrame(rows)
    df.to_csv(os.path.join(OUT, "claims_check.csv"), index=False)
    passed = bool(df.as_documented.all())
    counts = df.status.value_counts().to_dict()

    lines = ["# Verification report: SUSCON XIII full paper",
             "",
             "*Trash to Trust: Layer-Wise Validation of an Integrated Decision Framework for "
             "Circular and Equitable Municipal Solid Waste Management in India* (A. Kundu)",
             "",
             f"**Result: {'PASS' if passed else 'FAIL'}** - {int(df.as_documented.sum())} of {len(df)} "
             "claims landed in their documented status.",
             "",
             "PASS means every regenerated number matches the paper within its rounding and every known "
             "discrepancy is the one documented in `ERRATA.md`. It does not mean every sentence of the "
             "paper is correct.",
             "",
             "| Status | Claims |", "|---|---:|"]
    for s in ["REPRODUCED", "REPRODUCED_WITH_CORRECTION", "LEGACY_ONLY", "NOT_SUPPORTED", "MISMATCH", "ERROR"]:
        if counts.get(s):
            lines.append(f"| {s} | {counts[s]} |")
    manifest = os.path.join(OUT, "run_manifest.json")
    if os.path.exists(manifest):
        with open(manifest) as f:
            m = json.load(f)
        lines += ["", f"Run: {m.get('run_utc', '')} - Python {m.get('python', '').split()[0]} on "
                      f"{m.get('platform', '')} - {m.get('total_seconds', 0) / 60:.1f} min. "
                      f"Byte-identical to the paper's run: {m.get('identical_to_paper_run', '?')} of "
                      f"{m.get('reference_files', '?')} tables; numerically equal (rtol 1e-6): "
                      f"{m.get('numerically_equal_to_paper_run', '?')}."]
    lines += ["", "## Claim by claim", "",
              "| ID | Section | Claim | Paper | Regenerated | Status | Erratum |",
              "|---|---|---|---|---|---|---|"]
    for r in rows:
        flag = "" if r["as_documented"] else " **(unexpected)**"
        lines.append(f"| {r['id']} | {r['section']} | {r['claim']} | {r['paper_value']} | "
                     f"{r['regenerated_value']} | {r['status']}{flag} | {r['erratum']} |")
    lines += ["", "Evidence file for each row: `outputs/claims_check.csv`. Errata: `ERRATA.md`."]
    with open(os.path.join(ROOT, "VERIFICATION_REPORT.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

