"""Check every quantitative claim of the SUSCON XIII full paper against the
outputs regenerated by this repository.

    python verification/verify_claims.py

Each claim carries the value printed in the paper, a function that reads the
regenerated value from ``outputs/``, a tolerance matching the paper's rounding,
and the status this repository documents for it:

  REPRODUCED                  number regenerates and the paper describes it correctly
  REPRODUCED_WITH_CORRECTION  number regenerates, but the paper's description,
                              unit or scope needs the correction in ERRATA.md
  LEGACY_ONLY                 number exists only in a pre-pipeline output that no
                              code in this repository regenerates (kept in
                              reference/legacy_colab_a70d27d/ for audit)
  NOT_SUPPORTED               the code does not implement what the paper states

The run PASSES when every regenerated number matches the paper within tolerance
and every claim lands in its documented status. A PASS therefore means "the
paper's numbers are reproduced and every known discrepancy is documented", not
"every sentence of the paper is correct". Writes outputs/claims_check.csv and
VERIFICATION_REPORT.md.
"""
