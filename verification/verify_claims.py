LEGACY = os.path.join(ROOT, "reference", "legacy_colab_a70d27d")


def csv(name: str, base: str = OUT) -> pd.DataFrame:
    return pd.read_csv(os.path.join(base, name))


def cell(name, key_col, key, col, base=OUT):
    df = csv(name, base)
    return float(df.loc[df[key_col] == key, col].iloc[0])


def source(path: str) -> str:
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


@dataclass
class Claim:
    cid: str
    section: str
    statement: str
    paper: object                       # value printed in the paper (number or text)
    observe: Callable[[], object]       # regenerated value
    tol: Optional[float]                # absolute tolerance for numbers; None = exact/text
    expected: str                       # documented status
    evidence: str                       # file that holds the regenerated value
    erratum: str = ""                   # ERRATA.md id, if any


